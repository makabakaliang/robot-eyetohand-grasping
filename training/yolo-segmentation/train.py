from ultralytics import YOLO
from multiprocessing import freeze_support


if __name__ == '__main__':
    # ------------------------------------------------------------------
    # Windows 下多进程训练时建议保留这句
    # Linux 下保留也没问题
    # ------------------------------------------------------------------
    freeze_support()

    # ==============================================================
    # 一、总开关区（你最常改这里）
    # ==============================================================

    # ------------------------------------------------------------------
    # 是否启用“在线增强”
    #
    # True  :
    #   启用在线增强，但只启用“几何增强”
    #   不启用在线光照增强（因为你已经离线做过了）
    #
    # False :
    #   完全关闭在线增强
    #
    # 推荐：
    # - 你现在做了离线光照增强，建议这里设 True
    #   这样训练时只补几何变化
    # ------------------------------------------------------------------
    USE_ONLINE_AUG = False

    # ------------------------------------------------------------------
    # 是否从旧 best.pt 继续训练
    #
    # False :
    #   从官方预训练分割模型开始训练
    #
    # True  :
    #   从你之前训练出的 best.pt 继续训练
    # ------------------------------------------------------------------
    USE_CONTINUE_TRAIN = False

    # ------------------------------------------------------------------
    # 如果 USE_CONTINUE_TRAIN=True
    # 请把这里改成你之前训练出的 best.pt 路径
    # ------------------------------------------------------------------
    CONTINUE_WEIGHT_PATH = "runs/segment/disk_seg_light_aug_v1/weights/best.pt"

    # ------------------------------------------------------------------
    # 实验名称
    # 建议每次改参数都改个名字，方便对比
    # ------------------------------------------------------------------
    EXP_NAME = "disk_seg_offline_light_plus_online_geo_v1"

    # ------------------------------------------------------------------
    # 训练轮数
    #
    # 推荐：
    # - 第一次正式训练：80~150
    # - 继续训练：20~60
    #
    # 你当前这批数据 225 张，先用 100 比较合适
    # ------------------------------------------------------------------
    EPOCHS = 100

    # ------------------------------------------------------------------
    # 输入尺寸
    #
    # 推荐：
    # - 640：默认推荐
    # - 768：边缘分割不够细时再试
    # ------------------------------------------------------------------
    IMG_SIZE = 640

    # ------------------------------------------------------------------
    # Batch 大小
    #
    # 推荐：
    # - 8：常用
    # - 4：显存不足时
    # - 16：显存够大时
    # ------------------------------------------------------------------
    BATCH = 8

    # ------------------------------------------------------------------
    # workers 数量
    # Windows 建议不要太大
    # ------------------------------------------------------------------
    WORKERS = 2

    # ------------------------------------------------------------------
    # 是否启用 AMP 混合精度
    #
    # False 更稳
    # True 更快更省显存
    # ------------------------------------------------------------------
    AMP = False

    # ------------------------------------------------------------------
    # 训练数据配置文件
    # ------------------------------------------------------------------
    DATA_YAML = "data.yaml"

    # ------------------------------------------------------------------
    # 显卡
    # 单卡一般写 0
    # 如果不想指定，也可删掉 device 参数
    # ------------------------------------------------------------------
    DEVICE = 0

    # ------------------------------------------------------------------
    # patience：验证集多少轮不提升就早停
    # ------------------------------------------------------------------
    PATIENCE = 30

    # ------------------------------------------------------------------
    # 随机种子
    # ------------------------------------------------------------------
    SEED = 42

    # ==============================================================
    # 二、在线增强参数区
    # 规则：
    # 1. 离线已经做过的“光照类增强”全部关闭
    # 2. 在线只保留“几何增强”
    # ==============================================================

    if USE_ONLINE_AUG:
        # ----------------------------------------------------------
        # A. 光照类在线增强：全部关闭
        #
        # 原因：
        # 你已经通过离线增强做了：
        # - bright / dark
        # - contrast
        # - gamma
        # - shadow
        # - blur
        # - noise
        #
        # 所以这里不要再叠 hsv 类增强，防止重复过头
        # ----------------------------------------------------------
        hsv_h = 0.0
        hsv_s = 0.0
        hsv_v = 0.0

        # ----------------------------------------------------------
        # B. 几何类在线增强：保留
        #
        # 这些是离线增强没做的
        # 所以在线训练时继续补几何变化
        # ----------------------------------------------------------

        # 小角度旋转
        # 推荐 5~8
        degrees = 8.0

        # 轻微平移
        # 推荐 0.05~0.10
        translate = 0.08

        # 轻微缩放
        # 推荐 0.10~0.25
        scale = 0.20

        # 错切先不开
        shear = 0.0

        # 轻微透视
        perspective = 0.0008

        # 左右翻转保留
        fliplr = 0.5

        # 上下翻转先不开
        flipud = 0.0

        # Mosaic 保留，增强堆叠/遮挡鲁棒性
        mosaic = 0.5

        # Mixup 先关
        mixup = 0.0

        # CopyPaste 先关
        copy_paste = 0.0

        # 最后多少个 epoch 关闭 mosaic
        close_mosaic = 10

    else:
        # ----------------------------------------------------------
        # 完全关闭在线增强
        # ----------------------------------------------------------
        hsv_h = 0.0
        hsv_s = 0.0
        hsv_v = 0.0

        degrees = 0.0
        translate = 0.0
        scale = 0.0
        shear = 0.0
        perspective = 0.0

        fliplr = 0.0
        flipud = 0.0

        mosaic = 0.0
        mixup = 0.0
        copy_paste = 0.0
        close_mosaic = 0

    # ==============================================================
    # 三、加载模型
    # ==============================================================

    if USE_CONTINUE_TRAIN:
        # ----------------------------------------------------------
        # 从你之前训练好的 best.pt 继续训练
        # ----------------------------------------------------------
        model = YOLO(CONTINUE_WEIGHT_PATH)
        print(f"使用继续训练权重: {CONTINUE_WEIGHT_PATH}")
    else:
        # ----------------------------------------------------------
        # 从官方预训练分割模型开始
        # 推荐先用 yolo11s-seg.pt
        # ----------------------------------------------------------
        model = YOLO("yolo11s-seg.pt")
        print("使用官方预训练模型: yolo11s-seg.pt")

    # ==============================================================
    # 四、打印当前配置，方便检查
    # ==============================================================

    print("=" * 60)
    print("训练配置摘要")
    print("=" * 60)
    print(f"DATA_YAML           = {DATA_YAML}")
    print(f"USE_ONLINE_AUG      = {USE_ONLINE_AUG}")
    print(f"USE_CONTINUE_TRAIN  = {USE_CONTINUE_TRAIN}")
    print(f"EPOCHS              = {EPOCHS}")
    print(f"IMG_SIZE            = {IMG_SIZE}")
    print(f"BATCH               = {BATCH}")
    print(f"WORKERS             = {WORKERS}")
    print(f"AMP                 = {AMP}")
    print(f"DEVICE              = {DEVICE}")
    print(f"PATIENCE            = {PATIENCE}")
    print(f"SEED                = {SEED}")
    print(f"EXP_NAME            = {EXP_NAME}")
    print("-" * 60)
    print("在线增强参数：")
    print(f"hsv_h               = {hsv_h}")
    print(f"hsv_s               = {hsv_s}")
    print(f"hsv_v               = {hsv_v}")
    print(f"degrees             = {degrees}")
    print(f"translate           = {translate}")
    print(f"scale               = {scale}")
    print(f"shear               = {shear}")
    print(f"perspective         = {perspective}")
    print(f"fliplr              = {fliplr}")
    print(f"flipud              = {flipud}")
    print(f"mosaic              = {mosaic}")
    print(f"mixup               = {mixup}")
    print(f"copy_paste          = {copy_paste}")
    print(f"close_mosaic        = {close_mosaic}")
    print("=" * 60)

    # ==============================================================
    # 五、开始训练
    # ==============================================================

    results = model.train(
        # ----------------------------------------------------------
        # 数据配置
        # ----------------------------------------------------------
        data=DATA_YAML,

        # ----------------------------------------------------------
        # 基础训练参数
        # ----------------------------------------------------------
        epochs=EPOCHS,
        imgsz=IMG_SIZE,
        batch=BATCH,
        workers=WORKERS,
        amp=AMP,

        # ----------------------------------------------------------
        # 预训练 / 复现 / 设备
        # ----------------------------------------------------------
        pretrained=True,
        deterministic=True,
        seed=SEED,
        device=DEVICE,

        # ----------------------------------------------------------
        # 在线增强（按上面的总开关和规则自动决定）
        # ----------------------------------------------------------
        hsv_h=hsv_h,
        hsv_s=hsv_s,
        hsv_v=hsv_v,

        degrees=degrees,
        translate=translate,
        scale=scale,
        shear=shear,
        perspective=perspective,

        fliplr=fliplr,
        flipud=flipud,

        mosaic=mosaic,
        mixup=mixup,
        copy_paste=copy_paste,
        close_mosaic=close_mosaic,

        # ----------------------------------------------------------
        # 训练停止策略
        # ----------------------------------------------------------
        patience=PATIENCE,

        # ----------------------------------------------------------
        # 输出设置
        # ----------------------------------------------------------
        project="runs/segment",
        name=EXP_NAME,
        save=True,
        verbose=True
    )

    print("训练完成")